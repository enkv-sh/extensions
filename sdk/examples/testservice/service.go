// Package testservice supplies the local service used by the plugin examples.
package testservice

import (
	"crypto/subtle"
	"encoding/base64"
	"encoding/json"
	"errors"
	"io"
	"net/http"
	"strconv"
	"strings"
	"sync"
	"unicode/utf8"
)

// Config fixes the bearer token and namespace for a service. Token must contain
// 1–1024 bytes; Namespace must contain 1–64 lowercase letters, digits or hyphens.
// Service retains these strings. Close drops its token reference; immutable
// copies cannot be cleared.
type Config struct{ Token, Namespace string }

// Counts is a snapshot of live resource counts and successful mutation totals.
// Tokens and Values count resources still present; the other fields count all
// completed creates, retirements, writes and deletes, including lost replies.
// These observations grant no Product ownership or operation authority.
type Counts struct {
	Tokens, Values                          int
	TokenCreates, TokenRetires              uint64
	ValueCreates, ValueWrites, ValueDeletes uint64
}

type value struct {
	id   string
	body []byte
}

// Service is the in-memory example HTTP handler. Construct it with New; its zero
// value is not usable. Calls are serialized internally. Stop and join the HTTP
// server before Close to end request lifetimes and clear mutable stored values.
type Service struct {
	mu                   sync.Mutex
	config               Config
	tokens               map[string][]byte
	values               map[string]value
	counts               Counts
	loseToken, loseValue bool
	closed               bool
}

// New validates config and creates an empty service. The caller owns Close and
// the HTTP server lifetime. Tokens generated by this service are deterministic
// test values and must not be used as production credentials.
func New(config Config) (*Service, error) {
	if config.Token == "" || len(config.Token) > 1024 || !namespaceValid(config.Namespace) {
		return nil, errors.New("example service configuration invalid")
	}
	return &Service{config: config, tokens: make(map[string][]byte), values: make(map[string]value)}, nil
}

func namespaceValid(name string) bool {
	if len(name) == 0 || len(name) > 64 {
		return false
	}
	for _, c := range name {
		if c != '-' && (c < 'a' || c > 'z') && (c < '0' || c > '9') {
			return false
		}
	}
	return true
}

// Counts returns observations for the example's tests, not effect authority.
func (s *Service) Counts() Counts {
	s.mu.Lock()
	defer s.mu.Unlock()
	c := s.counts
	c.Tokens, c.Values = len(s.tokens), len(s.values)
	return c
}

// LoseNextTokenReply drops the next successful token-create reply after storing
// the token, by aborting the handler with http.ErrAbortHandler. This test control
// does not roll back the effect or authorize a retry.
func (s *Service) LoseNextTokenReply() {
	s.mu.Lock()
	defer s.mu.Unlock()
	s.loseToken = true
}

// LoseNextValueReply drops the next successful value-create/write reply after
// the mutation, by aborting the handler with http.ErrAbortHandler. The effect remains.
func (s *Service) LoseNextValueReply() {
	s.mu.Lock()
	defer s.mu.Unlock()
	s.loseValue = true
}

// Close clears mutable service-owned values after its HTTP server has joined.
// It is idempotent. Future requests receive 503; immutable token copies and
// response copies already handed to callers cannot be cleared here.
func (s *Service) Close() error {
	s.mu.Lock()
	defer s.mu.Unlock()
	for _, body := range s.tokens {
		clear(body)
	}
	for _, v := range s.values {
		clear(v.body)
	}
	clear(s.tokens)
	clear(s.values)
	s.config.Token = ""
	s.closed = true
	return nil
}

// ServeHTTP handles the bounded example token/value API with bearer-token and
// namespace checks. Counts observes successful mutations even when a reply is
// deliberately lost. It returns 503 after Close.
func (s *Service) ServeHTTP(w http.ResponseWriter, r *http.Request) {
	s.mu.Lock()
	defer s.mu.Unlock()
	if s.closed {
		w.WriteHeader(http.StatusServiceUnavailable)
		return
	}
	if subtle.ConstantTimeCompare([]byte(r.Header.Get("Authorization")), []byte("Bearer "+s.config.Token)) != 1 {
		w.WriteHeader(http.StatusUnauthorized)
		return
	}
	if r.URL.RawQuery != "" {
		w.WriteHeader(http.StatusBadRequest)
		return
	}
	switch {
	case r.Method == http.MethodGet && r.URL.Path == "/session":
		writeJSON(w, http.StatusOK, struct {
			Namespace string `json:"namespace"`
		}{s.config.Namespace})
	case r.URL.Path == "/tokens" && r.Method == http.MethodPost:
		s.createToken(w, r)
	case strings.HasPrefix(r.URL.Path, "/tokens/"):
		s.token(w, r, strings.TrimPrefix(r.URL.Path, "/tokens/"))
	case strings.HasPrefix(r.URL.Path, "/values/"):
		s.value(w, r)
	default:
		w.WriteHeader(http.StatusNotFound)
	}
}

func (s *Service) createToken(w http.ResponseWriter, r *http.Request) {
	var input struct {
		Namespace string `json:"namespace"`
		Subject   string `json:"subject"`
	}
	decoder := json.NewDecoder(http.MaxBytesReader(w, r.Body, 4096))
	decoder.DisallowUnknownFields()
	if decoder.Decode(&input) != nil || decoder.Decode(new(any)) != io.EOF || input.Namespace != s.config.Namespace ||
		input.Subject == "" || len(input.Subject) > 256 || !utf8.ValidString(input.Subject) {
		w.WriteHeader(http.StatusBadRequest)
		return
	}
	s.counts.TokenCreates++
	id := "t" + strconv.FormatUint(s.counts.TokenCreates, 10)
	// Deterministic binary values make the example's consumer checks independent.
	body := append([]byte{0, 255}, []byte(input.Namespace+"/"+input.Subject+"/"+id)...)
	s.tokens[id] = body
	if s.loseToken {
		s.loseToken = false
		panic(http.ErrAbortHandler)
	}
	writeToken(w, http.StatusCreated, id, body)
}

func (s *Service) token(w http.ResponseWriter, r *http.Request, id string) {
	body, found := s.tokens[id]
	if !found {
		w.WriteHeader(http.StatusNotFound)
		return
	}
	switch r.Method {
	case http.MethodGet:
		writeToken(w, http.StatusOK, id, body)
	case http.MethodDelete:
		clear(body)
		delete(s.tokens, id)
		s.counts.TokenRetires++
		w.WriteHeader(http.StatusNoContent)
	default:
		w.WriteHeader(http.StatusMethodNotAllowed)
	}
}

func writeToken(w http.ResponseWriter, status int, id string, body []byte) {
	writeJSON(w, status, struct {
		ID          string `json:"id"`
		ValueBase64 string `json:"value_base64"`
	}{id, base64.StdEncoding.EncodeToString(body)})
}

func (s *Service) value(w http.ResponseWriter, r *http.Request) {
	parts := strings.Split(strings.TrimPrefix(r.URL.Path, "/values/"), "/")
	if len(parts) != 2 || parts[0] != s.config.Namespace {
		w.WriteHeader(http.StatusNotFound)
		return
	}
	name, err := base64.RawURLEncoding.Strict().DecodeString(parts[1])
	if err != nil || len(name) > 256 || !utf8.Valid(name) {
		w.WriteHeader(http.StatusBadRequest)
		return
	}
	key := string(name)
	current, found := s.values[key]
	if r.Method == http.MethodGet {
		if !found {
			w.WriteHeader(http.StatusNotFound)
			return
		}
		valueHeaders(w, current.id)
		w.Header().Set("Content-Type", "application/octet-stream")
		if _, err := w.Write(current.body); err != nil {
			panic(http.ErrAbortHandler)
		}
		return
	}
	switch r.Method {
	case http.MethodPost:
		if found || r.Header.Get("If-None-Match") != "*" {
			w.WriteHeader(http.StatusPreconditionFailed)
			return
		}
	case http.MethodPut, http.MethodDelete:
		if !found || r.Header.Get("If-Match") != strconv.Quote(current.id) {
			w.WriteHeader(http.StatusPreconditionFailed)
			return
		}
	default:
		w.WriteHeader(http.StatusMethodNotAllowed)
		return
	}
	if r.Method == http.MethodDelete {
		clear(current.body)
		delete(s.values, key)
		s.counts.ValueDeletes++
		w.WriteHeader(http.StatusNoContent)
		return
	}
	body, err := io.ReadAll(http.MaxBytesReader(w, r.Body, 65536))
	if err != nil {
		clear(body)
		w.WriteHeader(http.StatusRequestEntityTooLarge)
		return
	}
	status := http.StatusNoContent
	if r.Method == http.MethodPost {
		s.counts.ValueCreates++
		current.id = "v" + strconv.FormatUint(s.counts.ValueCreates, 10)
		status = http.StatusCreated
	} else {
		s.counts.ValueWrites++
	}
	clear(current.body)
	current.body = body
	s.values[key] = current
	if s.loseValue {
		s.loseValue = false
		panic(http.ErrAbortHandler)
	}
	valueHeaders(w, current.id)
	w.WriteHeader(status)
}

func valueHeaders(w http.ResponseWriter, id string) {
	w.Header().Set("X-Resource-ID", id)
	w.Header().Set("ETag", strconv.Quote(id))
}

func writeJSON(w http.ResponseWriter, status int, value any) {
	w.Header().Set("Content-Type", "application/json")
	w.WriteHeader(status)
	if err := json.NewEncoder(w).Encode(value); err != nil {
		panic(http.ErrAbortHandler)
	}
}
