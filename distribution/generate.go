// Command generate derives Go source locations and development workspaces.
package main

import (
	"bytes"
	"crypto/sha256"
	"encoding/json"
	"errors"
	"flag"
	"fmt"
	"go/format"
	"html"
	"io"
	"io/fs"
	"os"
	"os/exec"
	"path"
	"path/filepath"
	"slices"
	"strings"
)

type moduleLocation struct {
	Selector      string `json:"selector"`
	Module        string `json:"module"`
	Repository    string `json:"repository"`
	RepositoryURL string `json:"repository_url"`
	Directory     string `json:"directory"`
	TagPrefix     string `json:"tag_prefix"`
}

type inventory struct {
	SchemaVersion int              `json:"schema_version"`
	Go            string           `json:"go"`
	Modules       []moduleLocation `json:"modules"`
}

func main() {
	root := flag.String("root", ".", "extensions repository root")
	check := flag.Bool("check", false, "check generated files without writing")
	flag.Parse()
	if flag.NArg() != 0 {
		fmt.Fprintln(os.Stderr, "unexpected argument")
		os.Exit(2)
	}
	if err := generate(*root, *check); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generate(root string, check bool) error {
	root, err := filepath.Abs(root)
	if err != nil {
		return err
	}
	body, err := os.ReadFile(filepath.Join(root, "distribution/modules.json"))
	if err != nil {
		return err
	}
	if err := rejectDuplicateFields(body); err != nil {
		return err
	}
	var inv inventory
	decoder := json.NewDecoder(bytes.NewReader(body))
	decoder.DisallowUnknownFields()
	if err := decoder.Decode(&inv); err != nil {
		return fmt.Errorf("invalid module inventory: %w", err)
	}
	if err := decoder.Decode(new(any)); err != io.EOF {
		return errors.New("trailing module inventory")
	}
	if err := validate(inv); err != nil {
		return err
	}
	outputs := make(map[string][]byte)
	var workspace strings.Builder
	workspaceOwners := make(map[string]string)
	fmt.Fprintf(&workspace, "// Code generated by distribution/generate.go; DO NOT EDIT.\ngo %s\n\nuse (\n", inv.Go)
	var table, failures, native strings.Builder
	native.WriteString("// Code generated by distribution/generate.go; DO NOT EDIT.\npackage nativeprocess\n\nvar nativeModuleSources = []struct { Selector, Module, Sibling, Directory string }{\n")
	failures.WriteString("// Code generated by distribution/generate.go; DO NOT EDIT.\npackage records\n\nvar failureModuleSources = []struct { Module, Selector string }{\n")
	fmt.Fprintf(&table, "// Code generated by distribution/generate.go; DO NOT EDIT.\npackage main\n\nconst moduleInventorySHA256 = %q\n\nvar moduleSources = []moduleSource{\n", fmt.Sprintf("%x", sha256.Sum256(body)))
	for _, row := range inv.Modules {
		metadata := row.Module + " git " + row.RepositoryURL + " " + row.Directory
		page := fmt.Sprintf("<!doctype html>\n<html><head><meta charset=\"utf-8\"><meta name=\"go-import\" content=\"%s\"><title>%s</title></head><body><p>Go module: %s</p></body></html>\n", html.EscapeString(metadata), html.EscapeString(row.Module), html.EscapeString(row.Module))
		outputs[filepath.Join(root, "distribution/go-import", strings.TrimPrefix(row.Module, "enkv.sh/"), "go-import.html")] = []byte(page)
		if row.Selector == "" {
			continue
		}
		local := "./" + row.Directory
		sibling := ""
		if row.Repository != "enkv-extensions" {
			local = "../" + row.Repository + "/" + row.Directory
		} else {
			sibling = row.Repository
		}
		fmt.Fprintf(&workspace, "\t%s\n", local)
		workspaceOwners[row.Module] = local
		fmt.Fprintf(&native, "{Selector:%q,Module:%q,Sibling:%q,Directory:%q},\n", row.Selector, row.Module, sibling, row.Directory)
		fmt.Fprintf(&failures, "{Module:%q, Selector:%q},\n", row.Module, row.Selector)
		fmt.Fprintf(&table, "{Selector:%q, Module:%q, Sibling:%q, Directory:%q},\n", row.Selector, row.Module, sibling, row.Directory)
	}
	failures.WriteString("}\n")
	native.WriteString("}\n")
	workspace.WriteString(")\n")
	replacements, err := workspaceReplacements(root, inv, workspaceOwners)
	if err != nil {
		return err
	}
	workspace.WriteString(replacements)
	table.WriteString("}\n")
	source, err := format.Source([]byte(table.String()))
	if err != nil {
		return err
	}
	failureSource, err := format.Source([]byte(failures.String()))
	if err != nil {
		return err
	}
	outputs[filepath.Join(filepath.Dir(root), "enkv-core/tests/shared/records/module_sources_generated.go")] = failureSource
	nativeSource, err := format.Source([]byte(native.String()))
	if err != nil {
		return err
	}
	outputs[filepath.Join(filepath.Dir(root), "enkv-core/compositions/full/testsupport/nativeprocess/module_sources_generated_test.go")] = nativeSource
	outputs[filepath.Join(root, "go.work")] = []byte(workspace.String())
	outputs[filepath.Join(filepath.Dir(root), "enkv-core/tests/shared/runner/module_sources_generated.go")] = source
	mappingRoot := filepath.Join(root, "distribution/go-import")
	err = filepath.WalkDir(mappingRoot, func(filename string, entry fs.DirEntry, walkErr error) error {
		if errors.Is(walkErr, os.ErrNotExist) && filename == mappingRoot {
			return nil
		}
		if walkErr != nil {
			return walkErr
		}
		if entry.IsDir() {
			return nil
		}
		if _, ok := outputs[filename]; ok {
			return nil
		}
		if check {
			return fmt.Errorf("unregistered mapping output: %s", filename)
		}
		if entry.Name() != "go-import.html" || !entry.Type().IsRegular() {
			return fmt.Errorf("unexpected mapping output: %s", filename)
		}
		return os.Remove(filename)
	})
	if err != nil {
		return err
	}
	var names []string
	for name := range outputs {
		names = append(names, name)
	}
	slices.Sort(names)
	for _, name := range names {
		expected := outputs[name]
		if check {
			actual, err := os.ReadFile(name)
			if err != nil || !bytes.Equal(actual, expected) {
				return fmt.Errorf("generated file differs: %s", name)
			}
			continue
		}
		if err := os.MkdirAll(filepath.Dir(name), 0755); err != nil {
			return err
		}
		if err := os.WriteFile(name, expected, 0644); err != nil {
			return err
		}
	}
	return nil
}

// Full graph loading can request the versioned go.mod of a workspace main.
// Bind those exact requirements to the same local owners as the use rows.
func workspaceReplacements(root string, inv inventory, owners map[string]string) (string, error) {
	type requirement struct{ Path, Version string }
	seen := make(map[requirement]bool)
	for _, row := range inv.Modules {
		if row.Selector == "" {
			continue
		}
		owner := filepath.Join(root, owners[row.Module])
		command := exec.Command("go", "mod", "edit", "-json", "-modfile="+filepath.Join(owner, "go.mod"))
		command.Dir = owner
		for _, entry := range os.Environ() {
			key, _, _ := strings.Cut(entry, "=")
			if key != "GOWORK" && key != "GOTOOLCHAIN" && key != "GOENV" && key != "GOFLAGS" {
				command.Env = append(command.Env, entry)
			}
		}
		command.Env = append(command.Env, "GOWORK=off", "GOTOOLCHAIN=local", "GOENV=off", "GOFLAGS=")
		body, err := command.Output()
		if err != nil {
			var failure *exec.ExitError
			if errors.As(err, &failure) {
				return "", fmt.Errorf("read workspace module %s: %w: %s", row.Module, err, failure.Stderr)
			}
			return "", fmt.Errorf("read workspace module %s: %w", row.Module, err)
		}
		var parsed struct {
			Module  struct{ Path string }
			Require []requirement
		}
		if err := json.Unmarshal(body, &parsed); err != nil {
			return "", err
		}
		if parsed.Module.Path != row.Module {
			return "", fmt.Errorf("workspace module identity differs: %s", row.Module)
		}
		for _, required := range parsed.Require {
			if owners[required.Path] != "" {
				seen[required] = true
			}
		}
	}
	rows := make([]requirement, 0, len(seen))
	for row := range seen {
		rows = append(rows, row)
	}
	slices.SortFunc(rows, func(a, b requirement) int {
		if a.Path != b.Path {
			return strings.Compare(a.Path, b.Path)
		}
		return strings.Compare(a.Version, b.Version)
	})
	if len(rows) == 0 {
		return "", nil
	}
	var result strings.Builder
	result.WriteString("\nreplace (\n")
	for _, row := range rows {
		fmt.Fprintf(&result, "\t%s %s => %s\n", row.Path, row.Version, owners[row.Path])
	}
	result.WriteString(")\n")
	return result.String(), nil
}

func validate(inv inventory) error {
	if inv.SchemaVersion != 1 || inv.Go != "1.27.0" || len(inv.Modules) == 0 {
		return errors.New("unsupported module inventory")
	}
	selectors := make(map[string]bool)
	for i, row := range inv.Modules {
		if row.Repository != "enkv-core" && row.Repository != "enkv-extensions" {
			return errors.New("unknown module repository")
		}
		expectedURL := "https://github.com/enkv-sh/" + strings.TrimPrefix(row.Repository, "enkv-")
		if row.RepositoryURL != expectedURL || !relative(row.Directory) || row.TagPrefix != row.Directory+"/" || !strings.HasPrefix(row.Module, "enkv.sh/") || !relative(strings.TrimPrefix(row.Module, "enkv.sh/")) {
			return errors.New("module ownership differs")
		}
		public := strings.HasPrefix(row.Module, "enkv.sh/sdk/") || strings.HasPrefix(row.Module, "enkv.sh/plugins/")
		if public != (row.Repository == "enkv-extensions") {
			return errors.New("module repository ownership differs")
		}
		if row.Selector != "" {
			if !relative(row.Selector) || selectors[row.Selector] {
				return errors.New("module selector differs")
			}
			selectors[row.Selector] = true
		}
		for _, prior := range inv.Modules[:i] {
			if overlaps(prior.Module, row.Module) || prior.Repository == row.Repository && overlaps(prior.Directory, row.Directory) || prior.Selector != "" && row.Selector != "" && overlaps(prior.Selector, row.Selector) {
				return errors.New("overlapping module ownership")
			}
		}
	}
	return nil
}
func relative(value string) bool {
	return value != "" && value != "." && value != ".." && !strings.HasPrefix(value, "../") && !path.IsAbs(value) && path.Clean(value) == value && !strings.ContainsAny(value, "\\ \t\r\n\x00")
}
func overlaps(first, second string) bool {
	return first == second || strings.HasPrefix(first, second+"/") || strings.HasPrefix(second, first+"/")
}

func rejectDuplicateFields(body []byte) error {
	decoder := json.NewDecoder(bytes.NewReader(body))
	var value func() error
	value = func() error {
		token, err := decoder.Token()
		if err != nil {
			return err
		}
		delimiter, ok := token.(json.Delim)
		if !ok {
			return nil
		}
		switch delimiter {
		case '{':
			seen := make(map[string]bool)
			for decoder.More() {
				key, err := decoder.Token()
				if err != nil {
					return err
				}
				name, ok := key.(string)
				if !ok || seen[name] {
					return errors.New("duplicate inventory field")
				}
				seen[name] = true
				if err := value(); err != nil {
					return err
				}
			}
		case '[':
			for decoder.More() {
				if err := value(); err != nil {
					return err
				}
			}
		default:
			return errors.New("invalid inventory delimiter")
		}
		_, err = decoder.Token()
		return err
	}
	return value()
}
